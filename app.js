  var dots   = el.querySelectorAll('.carousel-dots span');
  var prev   = el.querySelector('.carousel-prev');
  var next   = el.querySelector('.carousel-next');
  var total  = slides.length;
  if(!total) return;

  var cur = 0;
  var interval = parseInt(el.dataset.auto || '5000', 10);
  var timer = null;

