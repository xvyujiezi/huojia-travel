// 按名称查找详情（最长 key 匹配，避免「同盟山」歧义）
function findDetail(name){
  var key = null;
  for(var k in DETAIL_DB){
    if(k === name || name.indexOf(k) > -1 || k.indexOf(name) > -1){
      if(!key || k.length > key.length) key = k;
    }
  }
  return key ? DETAIL_DB[key] : null;
}

function showDetail(name){
  var data = findDetail(name);
  if(!data) return;

  // 若弹窗已存在则复用，否则创建
  var mask = document.getElementById('detailMask');
  if(!mask){
    mask = document.createElement('div');
    mask.id = 'detailMask';
    mask.className = 'detail-mask';
    mask.innerHTML = '<div class="detail-panel"><div class="detail-head"><h3></h3><button class="x" onclick="closeDetail()">×</button></div><div class="detail-body"></div></div>';
    mask.addEventListener('click', function(e){
      if(e.target === mask) closeDetail();
    });
    document.body.appendChild(mask);
  }

  mask.querySelector('.detail-head h3').textContent = name;
  mask.querySelector('.detail-body').innerHTML =
    '<span class="tag">' + data.tag + '</span>' +
    '<p>' + data.c.replace(/\n/g, '</p><p>') + '</p>';

  // 强制重排后再加 open，确保过渡动画生效
  void mask.offsetWidth;
  mask.classList.add('on');
  document.body.style.overflow = 'hidden';
}

function closeDetail(){
  var mask = document.getElementById('detailMask');
  if(mask){
    mask.classList.remove('on');
    document.body.style.overflow = '';
  }
}

